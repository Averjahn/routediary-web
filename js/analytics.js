/**
 * Счётчик посещаемости и цели — ровно столько, сколько нужно рекламе.
 *
 * ЗАЧЕМ. Без целей нейросеть Яндекса не может оптимизировать показы под
 * что-либо, кроме кликов: ей нечего оптимизировать. Мы платим за визиты
 * и получаем визиты, а сколько из них дошло до машины и до оплаты —
 * неизвестно никому.
 *
 * ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ.
 *
 * Вебвизора и записи форм. Приложение обещает, что сервер не может
 * прочитать поездки человека, и это правда — они зашифрованы в браузере.
 * Но обещание стоит дёшево, если рядом стоит счётчик, пишущий каждое
 * движение мыши. Поэтому включены только просмотры страниц и наши
 * собственные события, а `webvisor`, `trackHash` и сбор форм выключены
 * явным параметром, а не «по умолчанию».
 *
 * Событие — это ФАКТ, а не данные. «Человек добавил машину» уходит без
 * марки, модели и вообще без единого поля: Яндексу для обучения нужен
 * сам факт, а всё остальное — уже слежка.
 *
 * СЧЁТЧИК ВЫКЛЮЧЕН, ПОКА НЕ ЗАДАН НОМЕР. Никакого стороннего кода на
 * страницу не приезжает, пока в METRIKA_ID не появится настоящий номер.
 * Это не заглушка на будущее, а защита: подключить чужой скрипт «на
 * всякий случай» нельзя.
 */

/**
 * Номер счётчика Яндекс.Метрики. Пусто — счётчик не подключается вовсе.
 * Здесь, а не в настройках: номер публичный, он и так виден в коде любой
 * страницы, а хранить его в базе значит уметь его менять — незачем.
 */
export const METRIKA_ID = '';

/**
 * Цели. Названия — то, что увидит человек в интерфейсе Метрики, поэтому
 * они читаемые, а не сокращения.
 *
 * ЧЕМ ОПТИМИЗИРОВАТЬ КАМПАНИЮ. Не оплатой. Автостратегии учатся примерно
 * на десяти конверсиях в неделю, а оплат при нашем трафике будет
 * единицы — алгоритму не на чем строить закономерность. Мишенью надо
 * ставить `vehicle_added`: событий хватает уже на минимальном бюджете, и
 * оно осмысленное — человек завёл свою машину, значит правда попробовал.
 * Оплату считаем для отчётности, а не для обучения.
 */
export const GOALS = {
  APP_OPENED: 'app_opened',
  VEHICLE_ADDED: 'vehicle_added',
  TRIP_RECORDED: 'trip_recorded',
  PAYWALL_OPENED: 'paywall_opened',
  PURCHASE: 'purchase',
};

let ready = false;

/** Отправить цель. Молчит, если счётчик не подключён. */
export function goal(name) {
  if (!ready || typeof window === 'undefined') return false;
  try {
    window.ym?.(METRIKA_ID, 'reachGoal', name);
    return true;
  } catch {
    // Счётчик — не то, ради чего можно уронить приложение.
    return false;
  }
}

/**
 * Подключить счётчик.
 *
 * Вызывается один раз при запуске. Если номер не задан — не делает
 * ничего и не загружает ни байта постороннего кода.
 */
export function initAnalytics() {
  if (ready || !METRIKA_ID || typeof document === 'undefined') return false;

  window.ym = window.ym || function (...args) { (window.ym.a = window.ym.a || []).push(args); };
  window.ym.l = Date.now();

  const script = document.createElement('script');
  script.async = true;
  script.src = 'https://mc.yandex.ru/metrika/tag.js';
  document.head.appendChild(script);

  window.ym(METRIKA_ID, 'init', {
    // Просмотры страниц — да, всё остальное выключено осознанно.
    clickmap: false,
    trackLinks: false,
    accurateTrackBounce: true,
    webvisor: false,
    trackHash: false,
  });

  ready = true;
  goal(GOALS.APP_OPENED);
  return true;
}
